"""Core helpers for the knowledge base: YAML subset parsing, loading, rendering.

Stdlib only, by design. No PyYAML, no jsonschema, no network. The cost of that choice is
a restricted YAML subset (documented in AGENTS.md section 4); the benefit is that any agent
on any host can validate the whole knowledge base with `python3` and nothing else.
"""

